# Python Data Types

# String
name = "Solow"

# Integer
age = 20

# Float
height = 1.75

# Boolean
is_student = True

# Display the values
print(name)
print(age)
print(height)
print(is_student)

# Display the data types
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))

